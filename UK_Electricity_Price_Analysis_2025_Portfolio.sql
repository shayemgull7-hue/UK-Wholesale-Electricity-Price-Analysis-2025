-- UK Wholesale Electricity Price Analysis | 2025
-- Snowflake SQL portfolio script (annotated copy of the project workflow).
-- The script documents the steps used; it is NOT intended to be run all at once
-- against an already populated project, since CREATE TABLE statements will fail
-- if the tables already exist. CSV loading was completed interactively.
-- Units: prices GBP/MWh; national demand and embedded wind MW.
-- Market index prices are not day-ahead or imbalance settlement prices.

-- 01 | PROJECT SETUP
-- Create the database and schema. Run these statements only for initial setup.
create database UK_ELECTRICITY_2025;
create schema UK_ELECTRICITY_2025.ENERGY_ANALYSIS;

-- 02 | ELEXON MARKET INDEX PRICE TABLE
-- Source: Elexon Insights API, APXMIDP provider, half-hourly 2025 data.
-- PRICE_CLEAN was prepared upstream: 11 zero-volume observations are NULL;
-- genuine negative prices remain unchanged.
-- After table creation, import the cleaned price CSV using Snowflake's Load Data interface before running the validation query.
CREATE TABLE UK_ELECTRICITY_2025.ENERGY_ANALYSIS.ELECTRICITY_PRICES (
    STARTTIME TIMESTAMP_TZ,
    DATAPROVIDER VARCHAR(50),
    SETTLEMENTDATE DATE,
    SETTLEMENTPERIOD INTEGER,
    PRICE FLOAT,
    VOLUME FLOAT,
    PRICE_CLEAN FLOAT
);

SELECT 
    COUNT (*) AS TOTAL_RECORDS,
    MIN(SETTLEMENTDATE) AS EARLIEST_DATE,
    MAX(SETTLEMENTDATE) AS LATEST_DATE,
    COUNT_IF(PRICE_CLEAN IS NULL) AS MISSING_PRICES
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.ELECTRICITY_PRICES;


-- 03 | NESO HISTORIC DEMAND TABLE
-- Source: NESO Historic Demand Data 2025.
-- Import the NESO CSV with Snowflake Load Data after creating this table.
-- ND is national demand; embedded wind is not total GB wind generation.
CREATE TABLE UK_ELECTRICITY_2025.ENERGY_ANALYSIS.NESO_DEMAND_WIND (
    SETTLEMENT_DATE DATE,
    SETTLEMENT_PERIOD INTEGER,
    ND FLOAT,
    TSD FLOAT,
    ENGLAND_WALES_DEMAND FLOAT,
    EMBEDDED_WIND_GENERATION FLOAT,
    EMBEDDED_WIND_CAPACITY FLOAT,
    EMBEDDED_SOLAR_GENERATION FLOAT,
    EMBEDDED_SOLAR_CAPACITY FLOAT,
    NON_BM_STOR FLOAT,
    PUMP_STORAGE_PUMPING FLOAT,
    SCOTTISH_TRANSFER FLOAT,
    IFA_FLOW FLOAT,
    IFA2_FLOW FLOAT,
    BRITNED_FLOW FLOAT,
    MOYLE_FLOW FLOAT,
    EAST_WEST_FLOW FLOAT,
    NEMO_FLOW FLOAT,
    NSL_FLOW FLOAT,
    ELECLINK_FLOW FLOAT,
    VIKING_FLOW FLOAT,
    GREENLINK_FLOW FLOAT
);

SELECT
    COUNT(*) TOTAL_RECORDS,
    MIN(SETTLEMENT_DATE) AS EARLIEST_DATE,
    MAX(SETTLEMENT_DATE) AS LATEST_DATE,
    COUNT_IF(ND IS NULL) AS MISSING_DEMAND,
    COUNT_IF(EMBEDDED_WIND_GENERATION IS NULL) AS MISSING_WIND
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.NESO_DEMAND_WIND;

-- 04 | CHECK JOIN COVERAGE
-- Expect 17,520 matched settlement-date/settlement-period records.
SELECT 
    COUNT(*) AS MATCHED_RECORDS
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.ELECTRICITY_PRICES P
INNER JOIN UK_ELECTRICITY_2025.ENERGY_ANALYSIS.NESO_DEMAND_WIND N
    ON P.SETTLEMENTDATE=N.SETTLEMENT_DATE
    AND P.SETTLEMENTPERIOD=N.SETTLEMENT_PERIOD;

-- 05 | BUILD ANALYSIS TABLE
-- Join by settlement date and settlement period, preserving NULL prices.
CREATE TABLE UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND AS
SELECT
    P.SETTLEMENTDATE,
    P.SETTLEMENTPERIOD,
    P.PRICE_CLEAN AS ELECTRICITY_PRICE,
    P.VOLUME AS TRADED_VOLUME,
    N.ND AS ELECTRICITY_DEMAND,
    N.EMBEDDED_WIND_GENERATION AS WIND_GENERATION,
    N.EMBEDDED_SOLAR_GENERATION AS SOLAR_GENERATION
    
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.ELECTRICITY_PRICES P

INNER JOIN UK_ELECTRICITY_2025.ENERGY_ANALYSIS.NESO_DEMAND_WIND N
    ON P.SETTLEMENTDATE=N.SETTLEMENT_DATE
    AND P.SETTLEMENTPERIOD=N.SETTLEMENT_PERIOD;

select
    count(*) AS TOTAL_RECORDS,
    COUNT_IF(ELECTRICITY_PRICE IS NULL) AS MISSING_PRICES,
    COUNT_IF(ELECTRICITY_DEMAND IS NULL) AS MISSING_DEMAND,
    COUNT_IF(WIND_GENERATION IS NULL) AS MISSING_WIND
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;

-- 06 | SUMMARY PRICE STATISTICS
-- AVG ignores NULL prices (17,509 valid price observations).
SELECT
    ROUND(AVG(ELECTRICITY_PRICE),2) AS AVG_PRICE,
    MIN (ELECTRICITY_PRICE) AS MIN_PRICE,
    MAX (ELECTRICITY_PRICE) AS MAX_PRICE,
    COUNT_IF(ELECTRICITY_PRICE < 0) AS NEGATIVE_PRICE_PERIODS
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;

-- 07 | PRICE ASSOCIATIONS
-- Correlation describes association, not causation.
SELECT
    ROUND(CORR(WIND_GENERATION, ELECTRICITY_PRICE),3)
    AS WIND_PRICE_CORRELATION
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;


SELECT
    ROUND(CORR(ELECTRICITY_DEMAND, ELECTRICITY_PRICE), 3)
        AS DEMAND_PRICE_CORRELATION
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;


SELECT
    CASE
        WHEN ELECTRICITY_PRICE < 0 THEN 'Negative Price'
        ELSE 'Zero or Positive Price'
    END AS PRICE_CATEGORY,

    COUNT(*) AS TOTAL_PERIODS,

    ROUND(AVG(WIND_GENERATION), 2) AS AVG_WIND_MW,

    ROUND(AVG(ELECTRICITY_DEMAND), 2) AS AVG_DEMAND_MW

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND

WHERE ELECTRICITY_PRICE IS NOT NULL

GROUP BY PRICE_CATEGORY;


SELECT
    MONTH(SETTLEMENTDATE) AS MONTH_NUMBER,
    ROUND(AVG(ELECTRICITY_PRICE), 2) AS AVG_PRICE,
    COUNT_IF(ELECTRICITY_PRICE < 0) AS NEGATIVE_PRICE_PERIODS
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND
GROUP BY MONTH_NUMBER
ORDER BY MONTH_NUMBER;

SELECT
    FLOOR((SETTLEMENTPERIOD - 1) / 2) AS SETTLEMENT_HOUR,
    ROUND(AVG(ELECTRICITY_PRICE), 2) AS AVG_PRICE
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND
WHERE SETTLEMENTPERIOD BETWEEN 1 AND 48
GROUP BY SETTLEMENT_HOUR
ORDER BY SETTLEMENT_HOUR;

-- 08 | WIND QUARTILES
WITH WIND_GROUPS AS(
    SELECT
    ELECTRICITY_PRICE,
    WIND_GENERATION,
    NTILE(4) OVER (ORDER BY WIND_GENERATION) AS WIND_QUARTILE
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND
WHERE ELECTRICITY_PRICE IS NOT NULL
)
SELECT 
    WIND_QUARTILE,
    ROUND(MIN(WIND_GENERATION), 2) AS MIN_WIND_MW,
    ROUND(MAX(WIND_GENERATION), 2) AS MAX_WIND_MW,
    ROUND(AVG(ELECTRICITY_PRICE), 2) AS AVG_PRICE,
    COUNT(*) AS TOTAL_PERIODS
FROM WIND_GROUPS
GROUP BY WIND_QUARTILE
ORDER BY WIND_QUARTILE;


-- 09 | DEMAND QUARTILES
WITH DEMAND_GROUPS AS (
    SELECT
        ELECTRICITY_PRICE,
        ELECTRICITY_DEMAND,
        NTILE(4) OVER (ORDER BY ELECTRICITY_DEMAND) AS DEMAND_QUARTILE
    FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND
    WHERE ELECTRICITY_PRICE IS NOT NULL
)
SELECT
    DEMAND_QUARTILE,
    ROUND(MIN(ELECTRICITY_DEMAND), 2) AS MIN_DEMAND_MW,
    ROUND(MAX(ELECTRICITY_DEMAND), 2) AS MAX_DEMAND_MW,
    ROUND(AVG(ELECTRICITY_PRICE), 2) AS AVG_PRICE,
    COUNT(*) AS TOTAL_PERIODS
FROM DEMAND_GROUPS
GROUP BY DEMAND_QUARTILE
ORDER BY DEMAND_QUARTILE;

SELECT
    CASE
        WHEN WIND_GENERATION >=2500 THEN 'HIGH_WIND'
        ELSE 'LOW_WIND'
    END AS WIND_CATEGORY,
    CASE
        WHEN ELECTRICITY_DEMAND>=25000 THEN 'HIGH_DEMAND'
        ELSE 'LOW_DEMAND'
    END AS DEMAND_CATEGORY,
   
    COUNT(*) AS TOTAL_PERIODS,
    ROUND(AVG(ELECTRICITY_PRICE),2) AS AVG_PRICE
FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND
WHERE ELECTRICITY_PRICE IS NOT NULL
GROUP BY WIND_CATEGORY, DEMAND_CATEGORY
ORDER BY WIND_CATEGORY, DEMAND_CATEGORY;


SELECT
    CASE
        WHEN WIND_GENERATION >= 2500 THEN 'HIGH_WIND'
        ELSE 'LOW_WIND'
    END AS WIND_CATEGORY,

    CASE
        WHEN ELECTRICITY_DEMAND >= 25000 THEN 'HIGH_DEMAND'
        ELSE 'LOW_DEMAND'
    END AS DEMAND_CATEGORY,

    COUNT(*) AS TOTAL_PERIODS,

    COUNT_IF(ELECTRICITY_PRICE < 0) AS NEGATIVE_PERIODS,

    ROUND(
        100.0 * COUNT_IF(ELECTRICITY_PRICE < 0) / COUNT(*),
        2
    ) AS NEGATIVE_PRICE_PERCENT

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND

WHERE ELECTRICITY_PRICE IS NOT NULL

GROUP BY WIND_CATEGORY, DEMAND_CATEGORY

ORDER BY WIND_CATEGORY, DEMAND_CATEGORY;



SELECT
    CASE
        WHEN WIND_GENERATION >= 2500 THEN 'HIGH_WIND'
        ELSE 'LOW_WIND'
    END AS WIND_CATEGORY,

    ROUND(
        CORR(ELECTRICITY_DEMAND, ELECTRICITY_PRICE),
        3
    ) AS DEMAND_PRICE_CORRELATION,

    COUNT(*) AS TOTAL_PERIODS

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND

WHERE ELECTRICITY_PRICE IS NOT NULL

GROUP BY WIND_CATEGORY

ORDER BY WIND_CATEGORY;


SELECT
    COUNT(*) AS TOTAL_PERIODS,

    COUNT_IF(ELECTRICITY_PRICE > 200) AS PRICE_SPIKE_PERIODS,

    ROUND(
        100.0 * COUNT_IF(ELECTRICITY_PRICE > 200)
        / COUNT(*), 2
    ) AS SPIKE_PERCENTAGE,

    ROUND(
        AVG(CASE
            WHEN ELECTRICITY_PRICE > 200
            THEN WIND_GENERATION
        END), 2
    ) AS AVG_WIND_DURING_SPIKES,

    ROUND(
        AVG(CASE
            WHEN ELECTRICITY_PRICE > 200
            THEN ELECTRICITY_DEMAND
        END), 2
    ) AS AVG_DEMAND_DURING_SPIKES

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND

WHERE ELECTRICITY_PRICE IS NOT NULL;


SELECT
    CASE
        WHEN WIND_GENERATION >= 2500 THEN 'HIGH_WIND'
        ELSE 'LOW_WIND'
    END AS WIND_CATEGORY,

    CASE
        WHEN ELECTRICITY_DEMAND >= 25000 THEN 'HIGH_DEMAND'
        ELSE 'LOW_DEMAND'
    END AS DEMAND_CATEGORY,

    COUNT(*) AS TOTAL_PERIODS,

    COUNT_IF(ELECTRICITY_PRICE > 200) AS SPIKE_PERIODS,

    ROUND(
        100.0 * COUNT_IF(ELECTRICITY_PRICE > 200)
        / COUNT(*), 2
    ) AS SPIKE_PERCENTAGE

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND

WHERE ELECTRICITY_PRICE IS NOT NULL

GROUP BY WIND_CATEGORY, DEMAND_CATEGORY

ORDER BY WIND_CATEGORY, DEMAND_CATEGORY;


DESCRIBE TABLE UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;



-- 10 | FINAL POWER BI VIEW
-- High embedded wind: >= 2,500 MW; high demand: >= 25,000 MW.
-- Negative price: < 0 GBP/MWh; spike: > 200 GBP/MWh.
-- NULL price rows remain in the view; both event flags are 0 for those rows.
CREATE OR REPLACE VIEW
UK_ELECTRICITY_2025.ENERGY_ANALYSIS.POWERBI_ELECTRICITY_2025
AS

SELECT
    
SETTLEMENTDATE AS SETTLEMENT_DATE,
SETTLEMENTPERIOD AS SETTLEMENT_PERIOD,
    ELECTRICITY_PRICE,
    ELECTRICITY_DEMAND,
    WIND_GENERATION,

    CASE
        WHEN WIND_GENERATION >= 2500 THEN 'HIGH_WIND'
        ELSE 'LOW_WIND'
    END AS WIND_CATEGORY,

    CASE
        WHEN ELECTRICITY_DEMAND >= 25000 THEN 'HIGH_DEMAND'
        ELSE 'LOW_DEMAND'
    END AS DEMAND_CATEGORY,

    CASE
        WHEN ELECTRICITY_PRICE < 0 THEN 1
        ELSE 0
    END AS NEGATIVE_PRICE_FLAG,

    CASE
        WHEN ELECTRICITY_PRICE > 200 THEN 1
        ELSE 0
    END AS PRICE_SPIKE_FLAG

FROM UK_ELECTRICITY_2025.ENERGY_ANALYSIS.PRICE_DEMAND_WIND;


